function getFullChangelog() {
  const base = typeof CHANGELOG !== 'undefined' ? CHANGELOG : [];
  return [...base, ...CHANGELOG_V16_V18];
}

function renderChangelog() {
  const all = getFullChangelog();
  let html = '<div class="changelog"><h3>📝 更新日志</h3>';
  for (const v of all.slice().reverse()) {
    html += `<details class="changelog-version"><summary><b>v${v.version}「${v.name}」</b>（${v.lines}行）</summary><ul>`;
    for (const h of v.highlights) html += `<li>${h}</li>`;
    html += '</ul></details>';
  }
  html += '</div>';
  return html;
}
