function mergeManualV20() {
  if (typeof MANUAL_V19 === 'undefined') {
    // 没有 v19 手册时，创建全局手册数组
    if (typeof window !== 'undefined') window.MANUAL = MANUAL_V20.slice();
    return MANUAL_V20.length;
  }
  let n = 0;
  for (const ch of MANUAL_V20) {
    if (!MANUAL_V19.find(x => x.id === ch.id)) {
      MANUAL_V19.push(ch);
      n++;
    }
  }
  return n;
}

