// 自检：25 种 × 3 级 = 75 配置项；cost 键白名单；effectDesc/desc/flavor 齐全
// ═══════════════════════════════════════════════════════════════════════
function BuildingsV18SelfTest() {
  const errors = [];
  const ok = (cond, msg) => { if (!cond) errors.push(msg); };
  try {
    const COST_KEYS = ['iron','ice','rare','water','food','steel','tech','uranium','he3'];
    const ids = Object.keys(BUILDINGS_V18);
    ok(ids.length === 25, '建筑应为 25 种，实际 ' + ids.length);
    for (const id of ids) {
      const b = BUILDINGS_V18[id];
      ok(b.id === id, id + ' 的 id 字段不一致');
      ok(b.name && b.icon, id + ' 缺少 name/icon');
      ok(Array.isArray(b.levels) && b.levels.length === 4 && b.levels[0] === null,
        id + ' levels 应为 [null, L1, L2, L3]');
      ok(!!b.desc, id + ' 缺少 desc');
      ok(b.unlock && b.unlock.desc, id + ' 缺少 unlock.desc');
      for (let lv = 1; lv <= 3; lv++) {
        const L = b.levels[lv];
        const tag = id + ' Lv' + lv;
        ok(L && typeof L.cost === 'object', tag + ' 缺少 cost');
        for (const k of Object.keys((L && L.cost) || {}))
          ok(COST_KEYS.indexOf(k) !== -1, tag + ' cost 含非法资源键: ' + k);
        ok(typeof L.needPop === 'number' && L.needPop > 0, tag + ' needPop 非法');
        ok(typeof L.powerUse === 'number' && L.powerUse >= 0, tag + ' powerUse 非法');
        ok(L.effect && typeof L.effect === 'object', tag + ' 缺少 effect');
        ok(!!L.effectDesc && !!L.desc && !!L.flavor, tag + ' 缺少 effectDesc/desc/flavor');
      }
    }
    ok(BUILD_ORDER_V18.length === 25, 'BUILD_ORDER_V18 应为 25 项');
    const seen = {};
    for (const id of BUILD_ORDER_V18) {
      ok(!!BUILDINGS_V18[id], 'BUILD_ORDER_V18 含未知建筑: ' + id);
      ok(!seen[id], 'BUILD_ORDER_V18 重复: ' + id); seen[id] = 1;
    }
    ok(typeof mergeBuildingsV18 === 'function', 'mergeBuildingsV18 缺失');
  } catch (e) { errors.push('自检异常: ' + (e && e.message)); }
  return { pass: errors.length === 0, fail: errors.length, errors };
}

