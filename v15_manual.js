// 手册渲染
function renderV15Manual(sectionId) {
  const s = V15_MANUAL[sectionId];
  if (!s) return '<p>未知章节</p>';
  let html = `<h2>${s.title}</h2>`;
  for (const sec of s.sections) {
    html += `<div class="manual-sec"><h4>${sec.h}</h4>`;
    if (sec.body) html += `<p>${sec.body}</p>`;
    if (sec.table) {
      html += '<table class="manual-table">';
      for (const row of sec.table) {
        html += `<tr>${row.map(c => `<td>${c}</td>`).join('')}</tr>`;
      }
      html += '</table>';
    }
    html += '</div>';
  }
  return html;
}

function v15ManualIndex() {
  return Object.entries(V15_MANUAL).map(([id, s]) =>
    `<button class="manual-idx-btn" data-manual="${id}">${s.title}</button>`
  ).join('');
}

